(defn update
  "Update an IssuingCard by passing id.

  ## Parameters (required):
    - `id` [string]: IssuingCard id. ex: \"5656565656565656\"

  ## Parameters (optional):
    - `params` [map]:
      - `:status` [string, default nil]: You may block the IssuingCard by passing 'blocked' or activate by passing 'active' in the status
      - `:pin` [string, default nil]: You may unlock your physical card by passing its PIN. This is also the PIN you use to authorize a purhcase.
      - `:display-name` [string, default nil]: card displayed name. ex: \"ANTHONY EDWARD\"
      - `:rules` [list of maps, default nil]: list of maps with \"amount\": int, \"currencyCode\": string, \"id\": string, \"interval\": string, \"name\": string pairs.
      - `:tags` [list of strings, default nil]: list of strings for tagging
    - `user` [map, default nil]: Project or Organization map returned from starkinfra.user/project or starkinfra.user/organization. Only necessary if starkinfra.settings/user has not been set.

  ## Return:
    - target IssuingCard with updated attributes"
  ([id params]
   (patch-id @credentials (resource) params id))

  ([id params user]
   (patch-id user (resource) params id)))

(defn cancel
